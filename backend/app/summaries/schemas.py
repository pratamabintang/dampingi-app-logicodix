from datetime import date
from typing import Literal
from pydantic import (
    BaseModel,
    ConfigDict,
    Field,
    field_validator,
    model_validator,
)

class MoodSummaryRequest(BaseModel):
    """Input used by the weekly summary service."""

    model_config = ConfigDict(extra="forbid")

    period_start: date
    period_end: date

    @model_validator(mode="after")
    def validate_period(self):
        if self.period_start > self.period_end:
            raise ValueError("period_start must not be after period_end")
        return self


class MoodSummaryOut(BaseModel):
    """Public response for a weekly mood summary, now includes optional EPDS evaluation."""

    model_config = ConfigDict(extra="forbid")

    status: Literal["complete", "insufficient_data", "unavailable"]
    period_start: date
    period_end: date
    mood_count: int = Field(ge=0)
    overview: str | None = None
    # New optional fields for EPDS evaluation
    epds_score: int | None = None  # Total EPDS score calculated from mood/journal data
    risk_flag: Literal["low", "moderate", "high"] | None = None  # Derived risk level based on EPDS

    """Public response for a weekly mood summary."""

    model_config = ConfigDict(extra="forbid")

    status: Literal["complete", "insufficient_data", "unavailable"]
    period_start: date
    period_end: date
    mood_count: int = Field(ge=0)
    overview: str | None = None

class MoodSummaryAIOut(BaseModel):
    """Internal structured output generated by the AI."""

    model_config = ConfigDict(extra="forbid")

    overview: str


class EPDSResult(BaseModel):
    """Result of a simple EPDS‑like evaluation derived from mood data.
    This is a placeholder implementation – in a real app the EPDS would be
    calculated from a questionnaire answered by the mother.
    """

    model_config = ConfigDict(extra="forbid")

    score: int = Field(ge=0, le=30)
    risk_flag: Literal["low", "moderate", "high"]

    """Internal structured output generated by the AI."""

    model_config = ConfigDict(extra="forbid")

    overview: str

    @field_validator("overview")
    @classmethod
    def overview_not_blank(cls, value: str) -> str:
        value = value.strip()
        if not value:
            raise ValueError("overview must not be blank")
        return value