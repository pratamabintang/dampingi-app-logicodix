from datetime import date
from enum import Enum
from typing import Any, Literal

from pydantic import (
    BaseModel,
    ConfigDict,
    Field,
    field_validator,
    model_validator,
)


class MoodSummaryRequest(BaseModel):
    """Input used by the weekly mood summary service."""

    model_config = ConfigDict(extra="forbid")

    period_start: date
    period_end: date

    @model_validator(mode="after")
    def validate_period(self):
        if self.period_start > self.period_end:
            raise ValueError("period_start must not be after period_end")
        return self


class MoodSummaryOut(BaseModel):
    """Public response for a weekly mood summary."""

    model_config = ConfigDict(extra="forbid")

    status: Literal["complete", "insufficient_data", "unavailable"]
    period_start: date
    period_end: date
    mood_count: int = Field(ge=0)
    overview: str | None = None

    @model_validator(mode="after")
    def validate_summary(self):
        if self.period_start > self.period_end:
            raise ValueError("period_start must not be after period_end")

        if self.status == "complete":
            if self.mood_count == 0:
                raise ValueError("complete summary requires mood data")
            if not self.overview or not self.overview.strip():
                raise ValueError("complete summary requires a non-blank overview")

        elif self.status == "insufficient_data":
            if self.mood_count != 0 or self.overview is not None:
                raise ValueError("insufficient_data requires zero moods and no overview")

        elif self.status == "unavailable":
            if self.mood_count == 0 or self.overview is not None:
                raise ValueError("unavailable requires mood data and no overview")

        return self


class MoodSummaryAIOut(BaseModel):
    """Internal structured output generated by the AI."""

    model_config = ConfigDict(extra="forbid")

    overview: str

    @field_validator("overview")
    @classmethod
    def overview_not_blank(cls, value: str) -> str:
        value = value.strip()
        if not value:
            raise ValueError("overview must not be blank")
        return value


