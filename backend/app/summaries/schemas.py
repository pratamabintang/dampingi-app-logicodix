class Audience(str, Enum):
    MOTHER = "mother"
    COMPANION = "companion"
    PROFESSIONAL = "professional"


class MoodEntry(BaseModel):
    model_config = ConfigDict(extra="forbid")

    date: date
    mood: int = Field(ge=1, le=5)


class Coverage(BaseModel):
    model_config = ConfigDict(extra="forbid")

    mood_days: int = Field(ge=0)
    expected_days: int = Field(ge=1)
    companion_observation_days: int = Field(ge=0)
    epds_available: bool


class SummaryEPDS(BaseModel):
    model_config = ConfigDict(extra="forbid")
    id: str
    total_score: int = Field(ge=0, le=30)
    evaluation_mode: Literal["demo_only"]
    follow_up_required: bool
    immediate_review_required: bool
    disclaimer: str
    created_at: str


class WeeklySummaryInput(BaseModel):
    model_config = ConfigDict(extra="forbid")

    period_start: date
    period_end: date
    audience: Audience
    coverage: Coverage
    epds_assessment: SummaryEPDS | None = None
    mother_mood_entries: list[MoodEntry] = Field(default_factory=list)
    permitted_journal_items: list[dict[str, Any]] = Field(
        default_factory=list
    )
    permitted_companion_observations: list[dict[str, Any]] = Field(
        default_factory=list
    )

    @model_validator(mode="after")
    def validate_period_and_coverage(self):
        if self.period_end < self.period_start:
            raise ValueError("period_end cannot be earlier than period_start")

        expected_days = (self.period_end - self.period_start).days + 1

        if self.coverage.expected_days != expected_days:
            raise ValueError(
                "coverage.expected_days must match the inclusive period length"
            )

        if self.coverage.mood_days > expected_days:
            raise ValueError("mood_days cannot exceed expected_days")

        if self.coverage.companion_observation_days > expected_days:
            raise ValueError(
                "companion_observation_days cannot exceed expected_days"
            )

        return self


class SummarySourceRef(BaseModel):
    model_config = ConfigDict(extra="forbid")

    source_type: Literal[
        "mother_mood",
        "mother_journal",
        "companion_observation",
        "epds_assessment",
    ]
    source_id: str = Field(min_length=1)


class WeeklySummaryAIOut(BaseModel):
    """Structured output generated by the weekly summary AI."""

    model_config = ConfigDict(extra="forbid")

    overview: str | None
    limitations: list[str] = Field(default_factory=list)

    @field_validator("overview")
    @classmethod
    def overview_not_blank(cls, value: str | None) -> str | None:
        if value is not None:
            value = value.strip()
            if not value:
                raise ValueError("overview must not be blank")
        return value

    @field_validator("limitations")
    @classmethod
    def clean_limitations(cls, values: list[str]) -> list[str]:
        cleaned = [value.strip() for value in values]
        if any(not value for value in cleaned):
            raise ValueError("limitations must not contain blank values")
        return cleaned


class WeeklySummaryResponse(BaseModel):
    """Public response for a weekly summary."""

    model_config = ConfigDict(extra="forbid")

    schema_version: str = "1"
    period_start: date
    period_end: date
    audience: Audience
    status: Literal["completed", "partial", "failed"]
    overview: str | None
    limitations: list[str] = Field(default_factory=list)
    source_refs: list[SummarySourceRef] = Field(default_factory=list)
    prompt_version: str
    epds_assessment: SummaryEPDS | None = None

    @model_validator(mode="after")
    def validate_response(self):
        if self.period_end < self.period_start:
            raise ValueError("period_end cannot be earlier than period_start")

        if self.status == "completed" and not self.overview:
            raise ValueError("completed summary requires an overview")

        if self.status == "failed" and self.overview is not None:
            raise ValueError("failed summary must not contain an overview")

        return self
