class Audience(str, Enum):
    MOTHER = "mother"
    COMPANION = "companion"
    PROFESSIONAL = "professional"


class MoodEntry(BaseModel):
    model_config = ConfigDict(extra="forbid")

    date: date
    mood: int = Field(ge=1, le=5)


class Coverage(BaseModel):
    model_config = ConfigDict(extra="forbid")

    mood_days: int = Field(ge=0)
    expected_days: int = Field(ge=1)
    companion_observation_days: int = Field(ge=0)
    epds_available: bool


class WeeklySummaryInput(BaseModel):
    model_config = ConfigDict(extra="forbid")

    period_start: date
    period_end: date
    audience: Audience
    coverage: Coverage
    mother_mood_entries: list[MoodEntry] = Field(default_factory=list)
    permitted_journal_items: list[dict[str, Any]] = Field(
        default_factory=list
    )
    permitted_companion_observations: list[dict[str, Any]] = Field(
        default_factory=list
    )

    @model_validator(mode="after")
    def validate_period_and_coverage(self):
        if self.period_end < self.period_start:
            raise ValueError("period_end cannot be earlier than period_start")

        expected_days = (self.period_end - self.period_start).days + 1

        if self.coverage.expected_days != expected_days:
            raise ValueError(
                "coverage.expected_days must match the inclusive period length"
            )

        if self.coverage.mood_days > expected_days:
            raise ValueError("mood_days cannot exceed expected_days")

        if self.coverage.companion_observation_days > expected_days:
            raise ValueError(
                "companion_observation_days cannot exceed expected_days"
            )

        return self
